function story(
  title: string,
  summary: string,
  tags: [string, string, string],
  othersSee: [string, string, string],
  realNeeds: [string, string, string],
  hiddenTitle: string,
  hiddenBody: string,
  misunderstandingTitle: string,
  misunderstandingBody: string,
  actionTitle: string,
  actionNote: string,
): EditorialStory {
  return { title, summary, tags, othersSee, realNeeds, hiddenTitle, hiddenBody, misunderstandingTitle, misunderstandingBody, actionTitle, actionNote };
}

export function getBaziEditorialStory(element: ElementKey) {
  return baziStories[element];
}

export function getZodiacEditorialStory(sign: ZodiacSignKey) {
  return zodiacStories[sign];
}

function withoutBoundary(value: string) {
  return value.replace(/\s*这描述的是结构倾向，不是固定命运。?$/, "").trim();
}

